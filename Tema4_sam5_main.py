from Tema4_sam5_Triangle import calculate_triangle_area


def get_valid_input(prompt):
    """
    Получает корректный числовой ввод от пользователя.

    Аргументы:
    prompt -- текст приглашения для ввода

    Возвращает:
    Введенное число (положительное)
    """
    while True:
        try:
            value = float(input(prompt))
            if value <= 0:
                print("Значение должно быть положительным числом. Попробуйте еще раз.")
                continue
            return value
        except ValueError:
            print("Некорректный ввод. Пожалуйста, введите число.")


def main():
    print("Вычисление площади треугольника по формуле Герона")
    print("------------------------------------------------")

    # Получаем длины сторон от пользователя
    a = get_valid_input("Введите длину первой стороны: ")
    b = get_valid_input("Введите длину второй стороны: ")
    c = get_valid_input("Введите длину третьей стороны: ")

    # Вычисляем площадь
    area = calculate_triangle_area(a, b, c)

    # Выводим результат
    if area is None:
        print("\nОшибка: введенные значения не могут быть сторонами треугольника.")
        print("Сумма любых двух сторон должна быть больше третьей стороны.")
    else:
        print(f"\nПлощадь треугольника: {area:.2f} кв. ед.")


if __name__ == "__main__":
    main()
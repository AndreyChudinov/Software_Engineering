# Создание собственного класса исключения
class InvalidDataError(Exception):
    """
    Пользовательское исключение для обработки недопустимых данных.
    Наследуется от базового класса Exception.
    Используется в ситуациях, когда данные не соответствуют ожидаемым критериям.
    """
    pass


# Первая функция с использованием исключения
def check_age(age):
    """
    Проверяет корректность возраста.

    Args:
        age (int): Проверяемый возраст

    Returns:
        str: Сообщение о корректности возраста

    Raises:
        InvalidDataError: Если возраст вне допустимого диапазона (0-150)
    """
    if age < 0 or age > 150:
        # Выбрасываем исключение с описанием ошибки
        raise InvalidDataError("Возраст должен быть от 0 до 150")
    return f"Возраст {age} корректен"


# Вторая функция с использованием исключения
def check_positive(number):
    """
    Проверяет, что число является положительным.

    Args:
        number (int/float): Проверяемое число

    Returns:
        str: Сообщение о том, что число положительное

    Raises:
        InvalidDataError: Если число не является положительным
    """
    if number <= 0:
        # Выбрасываем исключение с описанием ошибки
        raise InvalidDataError("Число должно быть положительным")
    return f"Число {number} положительное"


# Демонстрация работы исключения в разных сценариях
try:
    # Успешные вызовы функций
    print(check_age(25))  # Корректный возраст
    print(check_positive(10))  # Корректное положительное число

    # Этот вызов вызовет исключение - отрицательный возраст
    print(check_age(-5))  # Вызовет InvalidDataError

except InvalidDataError as e:
    # Обработка исключения из функций check_age или check_positive
    print(f"Ошибка: {e}")
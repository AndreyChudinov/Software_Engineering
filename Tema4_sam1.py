# Импортируем класс datetime из модуля datetime для работы с датой и временем
from datetime import datetime

# Импортируем функцию sqrt (квадратный корень) из модуля math для математических вычислений
from math import sqrt


def main(**kwargs):
    """
    Главная функция для вычисления евклидова расстояния от начала координат до точек.

    Функция принимает произвольное количество именованных аргументов, где каждый аргумент
    представляет собой список из двух чисел [x, y], определяющих координаты точки на плоскости.

    Для каждой точки вычисляется расстояние по формуле: sqrt(x² + y²)

    Аргументы:
        **kwargs: произвольные именованные аргументы формата имя_точки=[x, y]

    Возвращает:
        None (результаты выводятся напрямую в консоль)
    """

    # Итерируемся по всем элементам словаря kwargs методом items()
    # Каждый элемент представляет собой кортеж (имя_точки, координаты)
    for key in kwargs.items():
        # Вычисляем евклидово расстояние от начала координат (0, 0) до точки (x, y)
        # key[1] - это список координат [x, y]
        # key[1][0] - координата x (первый элемент списка)
        # key[1][1] - координата y (второй элемент списка)
        # x**2 + y**2 - сумма квадратов координат
        # sqrt() - извлечение квадратного корня из суммы квадратов
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)

        # Выводим вычисленное расстояние в консоль
        print(result)


# Проверяем, запущен ли скрипт напрямую (а не импортирован как модуль)
# Это стандартный паттерн в Python для разделения кода выполнения и кода импорта
if __name__ == '__main__':
    # Фиксируем текущее время начала выполнения программы
    # datetime.now() возвращает объект datetime с текущей датой и временем
    start_time = datetime.now()

    # Вызываем функцию main с передачей именованных аргументов
    # Каждый аргумент представляет собой точку с координатами [x, y]
    # one=[10, 3]   - точка с именем "one" и координатами x=10, y=3
    # two=[5, 4]    - точка с именем "two" и координатами x=5, y=4
    # three=[15, 13] - точка с именем "three" и координатами x=15, y=13
    # four=[93, 53]  - точка с именем "four" и координатами x=93, y=53
    # five=[133, 15] - точка с именем "five" и координатами x=133, y=15
    main(
        one=[10, 3],
        two=[5, 4],
        three=[15, 13],
        four=[93, 53],
        five=[133, 15]
    )

    # Вычисляем время выполнения программы как разницу между текущим временем и временем старта
    # datetime.now() - start_time возвращает объект timedelta, представляющий продолжительность
    time_costs = datetime.now() - start_time

    # Выводим время выполнения программы в консоль с помощью f-строки
    # Переменная time_costs автоматически преобразуется в читаемый формат (часы:минуты:секунды.микросекунды)
    print(f"Время выполнения программы - {time_costs}")